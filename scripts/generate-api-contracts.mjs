async function main() {
  const specText = await fs.readFile(specPath, "utf8");
  const spec = parseDocument(specText).toJSON();

  assert(spec && typeof spec === "object", "Failed to parse OpenAPI spec.");
  assert(spec.paths && typeof spec.paths === "object", "OpenAPI spec is missing paths.");

  const totalOperations = countOperations(spec.paths);
  assert(
    totalOperations === EXPECTED_OPERATION_TOTAL,
    `Expected ${EXPECTED_OPERATION_TOTAL} operations, found ${totalOperations}.`,
  );

  const matchedPaths = new Set();
  const domainSpecs = DOMAIN_CONFIGS.map((domain) => {
    const selectedPathEntries = Object.entries(spec.paths).filter(([pathKey]) => matchesDomain(domain, pathKey));

    for (const [pathKey] of selectedPathEntries) {
      matchedPaths.add(pathKey);
    }

    const selectedPaths = Object.fromEntries(selectedPathEntries.map(([pathKey, pathItem]) => [pathKey, structuredClone(pathItem)]));
    const domainSpec = buildDomainSpec(spec, selectedPaths);
    const operationIds = collectOperationIds(selectedPaths);

    return {
      ...domain,
      spec: domainSpec,
      pathKeys: selectedPathEntries.map(([pathKey]) => pathKey),
      operationIds,
      operationCount: operationIds.length,
    };
  });

  const unmatchedPaths = Object.keys(spec.paths).filter((pathKey) => !matchedPaths.has(pathKey));
  assert(unmatchedPaths.length === 0, `Unmatched paths in slicing plan: ${unmatchedPaths.join(", ")}`);

  const slicedOperationTotal = domainSpecs.reduce((sum, domain) => sum + domain.operationCount, 0);
  assert(
    slicedOperationTotal === EXPECTED_OPERATION_TOTAL,
    `Expected ${EXPECTED_OPERATION_TOTAL} sliced operations, found ${slicedOperationTotal}.`,
  );

  await fs.rm(generatedRoot, { recursive: true, force: true });
  await fs.mkdir(manifestDir, { recursive: true });

  for (const domain of domainSpecs) {
    const domainDir = path.join(generatedRoot, domain.name);
    await fs.mkdir(domainDir, { recursive: true });

    const openapiOutputPath = path.join(domainDir, "openapi.yaml");
    const typesOutputPath = path.join(domainDir, "types.ts");
    const clientOutputPath = path.join(domainDir, "client.ts");

    await writeGeneratedYaml(
      openapiOutputPath,
      stringify(domain.spec, { lineWidth: 0 }),
      "Source: api_spec/openapi_v2.yaml",
    );

    runTool(resolveBin("openapi-typescript"), [openapiOutputPath, "--output", typesOutputPath]);
    runTool(resolveBin("openapi-zod-client"), [
      openapiOutputPath,
      "--output",
      clientOutputPath,
      "--api-client-name",
      domain.apiClientName,
      "--export-schemas",
      "--with-docs",
      "--with-description",
      "--group-strategy",
      "none",
    ]);

    await stabilizeZodClientTypes(clientOutputPath, domain.apiClientName);
    await applyGeneratedTsHeader(typesOutputPath, "Source: api_spec/openapi_v2.yaml");
    await applyGeneratedTsHeader(clientOutputPath, "Source: api_spec/openapi_v2.yaml");

    const domainIndex = [
      `export * from "./client";`,
      `export type * from "./types";`,
      "",
    ].join("\n");
    await writeGeneratedTs(
      path.join(domainDir, "index.ts"),
      domainIndex,
      `Domain: ${domain.name}`,
    );
  }

  const manifest = {
    sourceSpec: "api_spec/openapi_v2.yaml",
    operationTotal: EXPECTED_OPERATION_TOTAL,
    domains: domainSpecs.map((domain) => ({
      name: domain.name,
      exportName: domain.exportName,
      apiClientName: domain.apiClientName,
      prefixes: [...domain.prefixes],
      pathCount: domain.pathKeys.length,
      operationCount: domain.operationCount,
      operationIds: [...domain.operationIds],
      files: {
        openapi: `${domain.name}/openapi.yaml`,
        types: `${domain.name}/types.ts`,
        client: `${domain.name}/client.ts`,
        index: `${domain.name}/index.ts`,
      },
    })),
  };

  await fs.writeFile(path.join(manifestDir, "manifest.json"), `${JSON.stringify(manifest, null, 2)}\n`, "utf8");

  const manifestTs = [
    "export type GeneratedApiDomainManifest = {",
    "  name: string;",
    "  exportName: string;",
    "  apiClientName: string;",
    "  prefixes: readonly string[];",
    "  pathCount: number;",
    "  operationCount: number;",
    "  operationIds: readonly string[];",
    "  files: {",
    "    openapi: string;",
    "    types: string;",
    "    client: string;",
    "    index: string;",
    "  };",
    "};",
    "",
    "export type GeneratedApiContractManifest = {",
    "  sourceSpec: string;",
    "  operationTotal: number;",
    "  domains: readonly GeneratedApiDomainManifest[];",
    "};",
    "",
    `export const generatedApiContractManifest = ${JSON.stringify(manifest, null, 2)} as const satisfies GeneratedApiContractManifest;`,
    "",
  ].join("\n");
  await writeGeneratedTs(
    path.join(manifestDir, "index.ts"),
    manifestTs,
    "Source: api_spec/openapi_v2.yaml",
  );

  const generatedIndex = [
    ...domainSpecs.map((domain) => `export * as ${domain.exportName} from "./${domain.name}";`),
    'export { generatedApiContractManifest } from "./manifest";',
    "",
  ].join("\n");
  await writeGeneratedTs(
    path.join(generatedRoot, "index.ts"),
    generatedIndex,
    "Directory: common/src/api/generated",
  );

  const generatedHash = await hashDirectory(generatedRoot);
  await fs.writeFile(generatedHashPath, `${generatedHash}\n`, "utf8");
}

function buildDomainSpec(spec, selectedPaths) {
  const referencedComponents = collectReferencedComponents(selectedPaths);
  const components = buildComponentsSubset(spec.components ?? {}, referencedComponents);
  const securitySchemes = pickSecuritySchemes(spec.components?.securitySchemes ?? {}, selectedPaths);

  if (Object.keys(securitySchemes).length > 0) {
    components.securitySchemes = securitySchemes;
  }

  const tagNames = collectTagNames(selectedPaths);
  const domainSpec = {
    openapi: spec.openapi,
    info: structuredClone(spec.info),
    paths: selectedPaths,
    components,
  };

  if (spec.servers) {
    domainSpec.servers = structuredClone(spec.servers);
  }

  if (Array.isArray(spec.tags) && tagNames.size > 0) {
    domainSpec.tags = spec.tags
      .filter((tag) => typeof tag?.name === "string" && tagNames.has(tag.name))
      .map((tag) => structuredClone(tag));
  }

  return domainSpec;
}

function buildComponentsSubset(components, initialReferences) {
  const subset = {};
  const queue = [];
  const seen = new Set();

  for (const [section, names] of initialReferences.entries()) {
    for (const name of names) {
      queue.push([section, name]);
    }
  }

  while (queue.length > 0) {
    const [section, name] = queue.shift();
    const cacheKey = `${section}:${name}`;

    if (seen.has(cacheKey)) {
      continue;
    }

    seen.add(cacheKey);

    const sourceSection = components[section];
    assert(sourceSection && typeof sourceSection === "object", `Missing component section: ${section}`);

    const sourceComponent = sourceSection[name];
    assert(sourceComponent !== undefined, `Missing component reference: #/components/${section}/${name}`);

    if (!subset[section]) {
      subset[section] = {};
    }

    subset[section][name] = structuredClone(sourceComponent);

    const nestedReferences = collectReferencedComponents(sourceComponent);
    for (const [nestedSection, nestedNames] of nestedReferences.entries()) {
      for (const nestedName of nestedNames) {
        queue.push([nestedSection, nestedName]);
      }
    }
  }

  return subset;
}

function collectReferencedComponents(node, collected = new Map()) {
  if (Array.isArray(node)) {
    for (const item of node) {
      collectReferencedComponents(item, collected);
    }
    return collected;
  }

  if (!node || typeof node !== "object") {
    return collected;
  }

  if (typeof node.$ref === "string") {
    const match = node.$ref.match(/^#\/components\/([^/]+)\/([^/]+)$/);
    if (match) {
      const [, section, name] = match;
      if (!collected.has(section)) {
        collected.set(section, new Set());
      }

      collected.get(section).add(name);
    }
  }

  for (const value of Object.values(node)) {
    collectReferencedComponents(value, collected);
  }

  return collected;
}

function pickSecuritySchemes(allSecuritySchemes, selectedPaths) {
  const usedNames = new Set();

  for (const pathItem of Object.values(selectedPaths)) {
    if (!pathItem || typeof pathItem !== "object") {
      continue;
    }

    if (Array.isArray(pathItem.security)) {
      collectSecurityNames(pathItem.security, usedNames);
    }

    for (const [method, operation] of Object.entries(pathItem)) {
      if (!HTTP_METHODS.has(method) || !operation || typeof operation !== "object") {
        continue;
      }

      if (Array.isArray(operation.security)) {
        collectSecurityNames(operation.security, usedNames);
      }
    }
  }

  const subset = {};
  for (const name of [...usedNames].sort()) {
    const securityScheme = allSecuritySchemes[name];
    assert(securityScheme, `Missing security scheme: ${name}`);
    subset[name] = structuredClone(securityScheme);
  }

  return subset;
}

function collectSecurityNames(securityEntries, target) {
  for (const securityEntry of securityEntries) {
    if (!securityEntry || typeof securityEntry !== "object") {
      continue;
    }

    for (const securityName of Object.keys(securityEntry)) {
      target.add(securityName);
    }
  }
}

function collectTagNames(selectedPaths) {
  const tagNames = new Set();

  for (const pathItem of Object.values(selectedPaths)) {
    if (!pathItem || typeof pathItem !== "object") {
      continue;
    }

    for (const [method, operation] of Object.entries(pathItem)) {
      if (!HTTP_METHODS.has(method) || !operation || typeof operation !== "object") {
        continue;
      }

      if (Array.isArray(operation.tags)) {
        for (const tag of operation.tags) {
          if (typeof tag === "string") {
            tagNames.add(tag);
          }
        }
      }
    }
  }

  return tagNames;
}

function collectOperationIds(pathsObject) {
  const operationIds = [];

  for (const pathItem of Object.values(pathsObject)) {
    if (!pathItem || typeof pathItem !== "object") {
      continue;
    }

    for (const [method, operation] of Object.entries(pathItem)) {
      if (!HTTP_METHODS.has(method) || !operation || typeof operation !== "object") {
        continue;
      }

      assert(typeof operation.operationId === "string", `Missing operationId on ${method.toUpperCase()} operation.`);
      operationIds.push(operation.operationId);
    }
  }

  return operationIds;
}

function countOperations(pathsObject) {
  let count = 0;

  for (const pathItem of Object.values(pathsObject)) {
    if (!pathItem || typeof pathItem !== "object") {
      continue;
    }

    for (const method of Object.keys(pathItem)) {
      if (HTTP_METHODS.has(method)) {
        count += 1;
      }
    }
  }

  return count;
}

function matchesDomain(domain, pathKey) {
  return domain.prefixes.some((prefix) => pathKey.startsWith(prefix));
}

function resolveBin(toolName) {
  const suffix = process.platform === "win32" ? ".cmd" : "";
  return path.join(repoRoot, "node_modules", ".bin", `${toolName}${suffix}`);
}

function runTool(command, args) {
  const result = spawnSync(command, args, {
    cwd: repoRoot,
    encoding: "utf8",
    stdio: "pipe",
  });

  if (result.status !== 0) {
    const stderr = result.stderr?.trim();
    const stdout = result.stdout?.trim();
    throw new Error(`Command failed: ${[command, ...args].join(" ")}\n${stderr || stdout || "Unknown error"}`);
  }
}

async function stabilizeZodClientTypes(filePath, apiClientName) {
  const original = await fs.readFile(filePath, "utf8");

  const importLine = 'import { makeApi, Zodios, type ZodiosOptions } from "@zodios/core";';
  const typedImportLine =
    'import { makeApi, Zodios, type ZodiosEndpointDefinitions, type ZodiosInstance, type ZodiosOptions } from "@zodios/core";';

  assert(original.includes(importLine), `Unexpected Zodios import format in ${path.relative(repoRoot, filePath)}`);

  let updated = original.replace(importLine, typedImportLine);
  updated = updated.replace("export const schemas = {", "export const schemas: Record<string, z.ZodTypeAny> = {");
  updated = updated.replace("const endpoints = makeApi([", "const endpoints: ZodiosEndpointDefinitions = makeApi([");

  const apiExport = `export const ${apiClientName} = new Zodios(endpoints);`;
  const typedApiExport = `export const ${apiClientName}: ZodiosInstance<typeof endpoints> = new Zodios(endpoints);`;
  assert(updated.includes(apiExport), `Missing API export for ${apiClientName} in ${path.relative(repoRoot, filePath)}`);
  updated = updated.replace(apiExport, typedApiExport);

  const createApiClientExport = "export function createApiClient(baseUrl: string, options?: ZodiosOptions) {";
  const typedCreateApiClientExport =
    "export function createApiClient(baseUrl: string, options?: ZodiosOptions): ZodiosInstance<typeof endpoints> {";
  assert(
    updated.includes(createApiClientExport),
    `Missing createApiClient export in ${path.relative(repoRoot, filePath)}`,
  );
  updated = updated.replace(createApiClientExport, typedCreateApiClientExport);

  if (updated !== original) {
    await fs.writeFile(filePath, updated, "utf8");
  }
}

async function writeGeneratedTs(filePath, content, metadataLine) {
  const lines = [
    `/* ${GENERATED_HEADER}`,
    ` * ${metadataLine}`,
    " */",
    "",
    content,
  ];

  await fs.writeFile(filePath, lines.join("\n"), "utf8");
}

async function writeGeneratedYaml(filePath, content, metadataLine) {
  const lines = [`# ${GENERATED_HEADER}`, `# ${metadataLine}`, "", content];
  await fs.writeFile(filePath, lines.join("\n"), "utf8");
}

async function applyGeneratedTsHeader(filePath, metadataLine) {
  const original = await fs.readFile(filePath, "utf8");

  if (original.startsWith("/* Generated by npm run generate:api-contracts.")) {
    return;
  }

  await writeGeneratedTs(filePath, original, metadataLine);
}

async function hashDirectory(rootDir) {
  const filePaths = await listFiles(rootDir);
  const { createHash } = await import("node:crypto");
  const hash = createHash("sha256");

  for (const filePath of filePaths) {
    const relativePath = path.relative(rootDir, filePath).replaceAll(path.sep, "/");
    const fileContent = await fs.readFile(filePath);
    hash.update(relativePath);
    hash.update("\0");
    hash.update(fileContent);
    hash.update("\0");
  }

  return hash.digest("hex");
}

async function listFiles(rootDir) {
  const entries = await fs.readdir(rootDir, { withFileTypes: true });
  const nestedEntries = await Promise.all(
    entries
      .sort((left, right) => left.name.localeCompare(right.name))
      .map(async (entry) => {
        const fullPath = path.join(rootDir, entry.name);

        if (entry.isDirectory()) {
          return listFiles(fullPath);
        }

        return [fullPath];
      }),
  );

  return nestedEntries.flat();
}

function assert(condition, message) {
  if (!condition) {
    throw new Error(message);
  }
}